#!/usr/bin/env bun
/**
 * Build for dsh-bioviewer.
 *
 * Produces the two halves of a DSH dual-face plugin:
 *
 * - `lib/index.js` — the **host half** (a plain cordis plugin, ESM, Node target).
 *   Every `@deepseek-ai/*` specifier stays external because the host bundle
 *   provides them at runtime; the plugin profile never installs them.
 *
 * - `lib/client.js` — the **client half**, wrapped in the DSH web boot protocol
 *   (`window.__ModuleLoader__.load({ id, factory })`, see
 *   `@deepseek-ai/dsh-client-modules`). Executing the script only *registers* the
 *   factory; the module body runs at materialization.
 *
 * The client bundle is a classic script, not an ES module, and its `require` can
 * only resolve specifiers the shell already owns. We therefore keep exactly
 * `react`, `react-dom`, `react-dom/client` and `react/jsx-runtime` external
 * (the shell provides React 18) and bundle everything else — including Mol*.
 *
 * CSS is inlined as a string and injected from inside the factory, because the
 * bundle has no side-effect-free way to ship a stylesheet.
 *
 * Usage: `bun run scripts/build.ts [--no-minify]`
 */
import { mkdir, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = (await Bun.file(join(root, "package.json")).json()) as { name: string };
const pluginId = pkg.name;

const minify = !process.argv.includes("--no-minify");
const outDir = join(root, "lib");

/** Specifiers the DSH web shell resolves for plugin bundles. Everything else must be bundled. */
const CLIENT_EXTERNALS = ["react", "react-dom", "react-dom/client", "react/jsx-runtime"];

/**
 * Inline `.css` imports as a string default export so the bundle can inject
 * them at materialization time instead of relying on a separate asset route.
 */
const cssAsText: import("bun").BunPlugin = {
  name: "css-as-text",
  setup(build) {
    build.onLoad({ filter: /\.css$/ }, async (args) => ({
      contents: `export default ${JSON.stringify(await Bun.file(args.path).text())};`,
      loader: "js",
    }));
  },
};

async function buildHostHalf(): Promise<number> {
  const result = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    target: "node",
    format: "esm",
    minify,
    sourcemap: "none",
    external: ["@deepseek-ai/*"],
    naming: "[dir]/index.js",
    outdir: outDir,
    define: { "process.env.NODE_ENV": JSON.stringify(minify ? "production" : "development") },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("host half build failed");
  }
  return result.outputs.reduce((total, output) => total + output.size, 0);
}

async function buildClientHalf(): Promise<{ size: number; path: string }> {
  const result = await Bun.build({
    entrypoints: [join(root, "src/client/index.tsx")],
    target: "browser",
    format: "cjs",
    minify,
    sourcemap: "none",
    external: CLIENT_EXTERNALS,
    plugins: [cssAsText],
    define: { "process.env.NODE_ENV": JSON.stringify(minify ? "production" : "development") },
  });
  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("client half build failed");
  }
  const [output] = result.outputs;
  if (!output) throw new Error("client half build produced no output");
  const body = await output.text();

  // The registration handoff: `id` must equal the package name (the graph row key),
  // and the factory returns the bundle's export surface (`apply`, `inject`).
  const bundle = `// Generated by scripts/build.ts — do not edit.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(pluginId)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
${body}
		return module.exports;
	}
});
`;
  const outPath = join(outDir, "client.js");
  await Bun.write(outPath, bundle);
  return { size: Buffer.byteLength(bundle), path: outPath };
}

async function main(): Promise<void> {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const hostSize = await buildHostHalf();
  const client = await buildClientHalf();

  // Type declarations for the package `exports` map.
  const tsc = Bun.spawnSync(
    ["bunx", "tsc", "-p", "tsconfig.build.json"],
    { cwd: root, stdout: "inherit", stderr: "inherit" },
  );
  if (tsc.exitCode !== 0) throw new Error("declaration emit failed");

  const kb = (n: number) => `${(n / 1024).toFixed(1)} KiB`;
  console.log(`host   lib/index.js   ${kb(hostSize)}`);
  console.log(`client lib/client.js  ${kb(client.size)}${minify ? "" : "  (unminified)"}`);
}

await main();
