#!/usr/bin/env bun
/**
 * Regenerates `src/client/generated/molstudio-assets.ts` from the installed
 * `@molstudio/core`.
 *
 * Why this exists: 0.1.6 ships a WebAssembly isosurface engine whose packaged
 * defaults resolve their scripts relative to `import.meta.url`
 * (`dist/compute/wasm-core.js`: `new URL("../assets/molstudio-wasm-engine.wasm", import.meta.url)`;
 * `dist/compute/worker-engine.js`: `new Worker(new URL("./worker.js", import.meta.url), { type: "module" })`).
 * Our client half is a single classic script served from
 * `/plugins/<id>/client.js` with no sibling asset route, and Bun rewrites
 * `import.meta.url` to the *build machine's* `file://` path, so both defaults
 * fail in the shell (the worker silently falls back to the main thread and the
 * wasm `fetch` fails, leaving the engine `null`). Embedding the 54 KB wasm as
 * a base64 data URL and the worker as a blob-URL source keeps the plugin
 * self-contained: nothing is fetched from the host at runtime.
 *
 * The wasm bytes and the worker are pinned to the installed package; the
 * generated module records their digests and `tests/wasm-asset.test.ts` fails
 * when the package moves without this script being re-run.
 *
 * Usage: `bun run sync:molstudio-assets`
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outputFile = join(repoRoot, "src/client/generated/molstudio-assets.ts");

/** The module entry `@molstudio/core` resolves to, then its package root. */
function coreRoot(): string {
  const entry = Bun.resolveSync("@molstudio/core", repoRoot);
  return dirname(dirname(entry));
}

function sha256(bytes: Uint8Array): string {
  return new Bun.CryptoHasher("sha256").update(bytes).digest("hex");
}

const root = coreRoot();
const manifest = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as { version: string };
const wasmPath = join(root, "dist/assets/molstudio-wasm-engine.wasm");
const workerPath = join(root, "dist/compute/worker.js");
const wasmCorePath = join(root, "dist/compute/wasm-core.js");

const [wasmBytes, workerSource, wasmCoreSource] = await Promise.all([
  readFile(wasmPath),
  readFile(workerPath),
  readFile(wasmCorePath),
]);

// The worker must arrive as one classic script: it runs from a blob URL in the
// page, so a module worker would need its `./wasm-core.js` import resolved.
const workerBuild = await Bun.build({
  entrypoints: [workerPath],
  target: "browser",
  format: "iife",
  minify: true,
  sourcemap: "none",
});
const workerBundle = workerBuild.outputs[0];
if (!workerBuild.success || workerBundle === undefined) {
  throw new Error(`could not bundle ${workerPath}: ${workerBuild.logs.join("\n")}`);
}
const workerBundleSource = await workerBundle.text();
// `new Function` only compiles: a syntax error here would reach the browser as
// an opaque worker `onerror` instead of a build failure.
new Function(workerBundleSource);

const source = (paths: string): string => relative(repoRoot, join(root, paths));
const generated = `/**
 * Generated by \`bun run sync:molstudio-assets\` — do not edit by hand.
 *
 * Ships @molstudio/core's wasm surface engine inside this plugin's single
 * classic-script client bundle, because the packaged 0.1.6 defaults resolve
 * their wasm/worker URLs from \`import.meta.url\` and the DSH shell serves no
 * sibling assets (see the sync script's header and AGENTS.md).
 *
 * Source: @molstudio/core@${manifest.version}
 * wasm:   ${source("dist/assets/molstudio-wasm-engine.wasm")} (${wasmBytes.byteLength} bytes)
 * worker: ${source("dist/compute/worker.js")} + ${source("dist/compute/wasm-core.js")}, bundled as one IIFE
 */

/** Installed \`@molstudio/core\` version these assets were extracted from. */
export const MOLSTUDIO_CORE_VERSION = ${JSON.stringify(manifest.version)};

/** Size of \`molstudio-wasm-engine.wasm\`, for docs and anti-drift assertions. */
export const MOLSTUDIO_WASM_BYTES = ${wasmBytes.byteLength};

/** sha256 of the wasm module, so a package bump cannot ride along unnoticed. */
export const MOLSTUDIO_WASM_SHA256 = ${JSON.stringify(sha256(wasmBytes))};

/** sha256 of \`dist/compute/worker.js\` when the worker bundle was built. */
export const MOLSTUDIO_WORKER_SHA256 = ${JSON.stringify(sha256(workerSource))};

/** sha256 of \`dist/compute/wasm-core.js\` when the worker bundle was built. */
export const MOLSTUDIO_WASM_CORE_SHA256 = ${JSON.stringify(sha256(wasmCoreSource))};

/** The wasm module as a base64 data URL payload. */
export const MOLSTUDIO_WASM_BASE64 = ${JSON.stringify(wasmBytes.toString("base64"))};

/** Classic-worker source for the engine's worker tier. */
export const MOLSTUDIO_SURFACE_WORKER_SOURCE = ${JSON.stringify(workerBundleSource)};
`;

await writeFile(outputFile, generated);
console.log(`wrote ${relative(repoRoot, outputFile)}: @molstudio/core@${manifest.version}, ${wasmBytes.byteLength} byte wasm, ${workerBundleSource.length} byte worker`);
